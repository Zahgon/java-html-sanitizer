// Command canned-tables generates sanitizer/html_element_tables_canned.go,
// the element tables the sanitizer balances tags with, from the browser
// observations in empiricism/canned-data.json.
//
// Usage:
//
//	canned-tables [infile.json [outfile.go]]
//
// The input defaults to canned-data.json and the output to
// target/html_element_tables_canned.go, both relative to the working
// directory.  The go:generate directive in sanitizer/html_element_tables.go
// runs it with both paths given, and empiricism/rebuild.sh runs that
// directive.
//
// The command uses only the standard library, so it still builds when the
// generated file it replaces is stale or missing.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"io"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

// customElementName is the placeholder name for any element name not in the
// element name list, as in sanitizer.HTMLElementTablesHTMLElementNames.
const customElementName = "xcustom"

// modelBits maps the text content model keys in the input to the bit masks
// of sanitizer.HTMLElementTablesTextContentModelBit.
var modelBits = map[string]byte{
	"comments":   1,
	"entities":   2,
	"raw":        4,
	"text":       8,
	"unended":    16,
	"plain_text": 32,
}

func main() {
	argv := os.Args[1:]
	if len(argv) > 2 || len(argv) > 0 && !isFile(argv[0]) {
		fmt.Fprintln(os.Stderr, "Expected infile.json outfile.go")
		fmt.Fprintln(os.Stderr)
		fmt.Fprintln(os.Stderr,
			"Converts canned-data.json to a serialized sanitizer.HTMLElementTables")
		os.Exit(1)
	}

	infile := "canned-data.json"
	if len(argv) >= 1 {
		infile = argv[0]
	}
	outfile := filepath.Join("target", "html_element_tables_canned.go")
	if len(argv) >= 2 {
		outfile = argv[1]
	}

	if err := run(infile, outfile); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func isFile(path string) bool {
	info, err := os.Stat(path)
	return err == nil && info.Mode().IsRegular()
}

// run reads the observations from infile and writes the generated source to
// outfile, creating its directory if need be.
func run(infile, outfile string) error {
	in, err := os.ReadFile(infile)
	if err != nil {
		return err
	}
	obj, err := parseObject(in)
	if err != nil {
		return fmt.Errorf("%s: %w", infile, err)
	}
	src, err := generate(obj)
	if err != nil {
		return fmt.Errorf("%s: %w", infile, err)
	}
	if dir := filepath.Dir(outfile); dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
	}
	return os.WriteFile(outfile, src, 0o644)
}

// generate returns the gofmt-formatted source of
// html_element_tables_canned.go for the observations in obj.
func generate(obj *object) ([]byte, error) {
	src := &sourceWriter{}
	src.lines(
		"// SPDX-License-Identifier: Apache-2.0 OR BSD-2-Clause",
		"// Code generated by empiricism/cmd/canned-tables from empiricism/canned-data.json; DO NOT EDIT.",
		"// Ported from owasp-java-html-sanitizer/src/main/java/org/owasp/html/HtmlElementTablesCanned.java.",
		"",
		"package sanitizer",
		"",
		"// htmlElementTablesCannedTables holds the element tables measured in a",
		"// browser by empiricism/html-containment.html.",
		"var htmlElementTablesCannedTables = func() *HTMLElementTables {",
	)

	nameArr, err := obj.array("elementNames")
	if err != nil {
		return nil, err
	}
	canonNames := make([]string, len(nameArr))
	for i, v := range nameArr {
		if canonNames[i], err = asString(v); err != nil {
			return nil, err
		}
	}
	en, err := newElementNames(canonNames)
	if err != nil {
		return nil, err
	}
	src.line("elementNames := NewHTMLElementTablesHTMLElementNames(")
	src.writeStrings(canonNames)
	src.line(")")

	for _, field := range []string{"canContain", "closedOnClose", "closedOnOpen"} {
		if err := newDenseElementBinaryMatrix(en, obj, field, src); err != nil {
			return nil, err
		}
	}
	if err := newSparseElementToElements(en, obj, "explicitClosers", src); err != nil {
		return nil, err
	}
	if err := newSparseElementMultitable(en, obj, "impliedElements", src); err != nil {
		return nil, err
	}
	if err := newTextContentModel(en, obj, "textContentModel", src); err != nil {
		return nil, err
	}
	if err := newDenseElementSet(en, obj, "resumable", src); err != nil {
		return nil, err
	}

	src.lines(
		"return NewHTMLElementTables(",
		"elementNames,",
		"canContain,",
		"closedOnClose,",
		"closedOnOpen,",
		"explicitClosers,",
		"impliedElements,",
		"textContentModel,",
		"resumable,",
		")",
		"}()",
	)
	return format.Source(src.buf.Bytes())
}

// elementNames maps element names to indices as
// sanitizer.HTMLElementTablesHTMLElementNames does.
type elementNames struct {
	canonNames         []string
	canonNameToIndex   map[string]int
	customElementIndex int
}

func newElementNames(canonNames []string) (*elementNames, error) {
	en := &elementNames{
		canonNames:         canonNames,
		canonNameToIndex:   make(map[string]int, len(canonNames)),
		customElementIndex: slices.Index(canonNames, customElementName),
	}
	for i, name := range canonNames {
		en.canonNameToIndex[name] = i
	}
	if en.customElementIndex < 0 {
		return nil, errors.New("Negative element index")
	}
	return en, nil
}

// index is the index of the given element name or otherwise the index of
// the custom element name.
func (en *elementNames) index(canonName string) int {
	if i, ok := en.canonNameToIndex[canonName]; ok {
		return i
	}
	return en.customElementIndex
}

func newTextContentModel(en *elementNames, obj *object, fieldName string, src *sourceWriter) error {
	tcmObj, err := obj.object(fieldName)
	if err != nil {
		return err
	}
	packedBits := make([]byte, len(en.canonNames))
	for _, key := range tcmObj.keys {
		ei := en.index(key)
		var b byte
		bitsObj, err := tcmObj.object(key)
		if err != nil {
			return err
		}
		for _, bitKey := range bitsObj.keys {
			mbit, ok := modelBits[bitKey]
			if !ok {
				return fmt.Errorf("unknown text content model bit %q", bitKey)
			}
			on, err := bitsObj.boolean(bitKey)
			if err != nil {
				return err
			}
			if on {
				b |= mbit
			} else {
				b &^= mbit
			}
		}
		packedBits[ei] = b
	}
	src.line(fieldName + " := NewHTMLElementTablesTextContentModel(")
	src.writeBytes(packedBits)
	src.line(")")
	return nil
}

func newDenseElementBinaryMatrix(en *elementNames, obj *object, fieldName string, src *sourceWriter) error {
	matrix, err := obj.object(fieldName)
	if err != nil {
		return err
	}
	dim := len(en.canonNames)
	bits := make([]bool, dim*dim)
	for _, elname := range matrix.keys {
		ai := en.index(elname)
		arr, err := matrix.array(elname)
		if err != nil {
			return err
		}
		for _, v := range arr {
			name, err := asString(v)
			if err != nil {
				return err
			}
			bits[ai*dim+en.index(name)] = true
		}
	}
	src.line(fieldName + " := newHTMLElementTablesDenseElementBinaryMatrix(")
	src.writePacked(bits)
	src.line(strconv.Itoa(dim) + ",")
	src.line(")")
	return nil
}

func newDenseElementSet(en *elementNames, obj *object, fieldName string, src *sourceWriter) error {
	set, err := obj.object(fieldName)
	if err != nil {
		return err
	}
	bits := make([]bool, len(en.canonNames))
	for _, elname := range set.keys {
		if bits[en.index(elname)], err = set.boolean(elname); err != nil {
			return err
		}
	}
	src.line(fieldName + " := NewHTMLElementTablesDenseElementSet(")
	src.writePacked(bits)
	src.line(")")
	return nil
}

func newSparseElementToElements(en *elementNames, obj *object, fieldName string, src *sourceWriter) error {
	closers, err := obj.object(fieldName)
	if err != nil {
		return err
	}
	var arrs [][]int
	for _, elname := range closers.keys {
		arr, err := closers.array(elname)
		if err != nil {
			return err
		}
		// The names form a set, and each maps to an index; two unknown names
		// map to the same one, which the table's constructor rejects.
		var names []string
		for _, v := range arr {
			name, err := asString(v)
			if err != nil {
				return err
			}
			if !slices.Contains(names, name) {
				names = append(names, name)
			}
		}
		ints := make([]int, 0, len(names)+1)
		ints = append(ints, en.index(elname))
		for _, name := range names {
			ints = append(ints, en.index(name))
		}
		slices.Sort(ints[1:])
		arrs = append(arrs, ints)
	}
	slices.SortStableFunc(arrs, compareByZeroth)
	src.line(fieldName + ", err := NewHTMLElementTablesSparseElementToElements(")
	src.line("[][]int{")
	for _, arr := range arrs {
		src.line("{")
		src.writeInts(arr)
		src.line("},")
	}
	src.line("},")
	src.line(")")
	src.panicOnError()
	return nil
}

func newSparseElementMultitable(en *elementNames, obj *object, fieldName string, src *sourceWriter) error {
	table, err := obj.object(fieldName)
	if err != nil {
		return err
	}
	arrs := make([][][]int, len(en.canonNames))
	for _, elname := range table.keys {
		ei := en.index(elname)
		subtable, err := table.object(elname)
		if err != nil {
			return err
		}
		tableArr := make([][]int, 0, len(subtable.keys))
		for _, elnameb := range subtable.keys {
			els, err := subtable.array(elnameb)
			if err != nil {
				return err
			}
			row := make([]int, 0, len(els)+1)
			row = append(row, en.index(elnameb))
			for _, v := range els {
				name, err := asString(v)
				if err != nil {
					return err
				}
				row = append(row, en.index(name))
			}
			tableArr = append(tableArr, row)
		}
		slices.SortStableFunc(tableArr, compareByZeroth)
		arrs[ei] = tableArr
	}
	// The first table above declared err.
	src.line(fieldName + ", err := NewHTMLElementTablesSparseElementMultitable(")
	src.line("[][][]int{")
	for _, arr := range arrs {
		if arr == nil {
			src.line("nil,")
			continue
		}
		src.line("{")
		for _, row := range arr {
			src.line("{")
			src.writeInts(row)
			src.line("},")
		}
		src.line("},")
	}
	src.line("},")
	src.line(")")
	src.panicOnError()
	return nil
}

func compareByZeroth(a, b []int) int {
	return a[0] - b[0]
}

// sourceWriter accumulates generated source, one line at a time, leaving
// indentation to gofmt.
type sourceWriter struct {
	buf bytes.Buffer
}

func (w *sourceWriter) lines(lines ...string) {
	for _, line := range lines {
		w.line(line)
	}
}

func (w *sourceWriter) line(line string) {
	w.buf.WriteString(line)
	w.buf.WriteByte('\n')
}

// writeEls writes n elements, sixteen to a line, each followed by a comma.
func (w *sourceWriter) writeEls(n int, el func(i int) string) {
	var buf strings.Builder
	for i := 0; i < n; i++ {
		if i != 0 {
			if i%16 == 0 {
				w.line(buf.String())
				buf.Reset()
			} else {
				buf.WriteByte(' ')
			}
		}
		buf.WriteString(el(i))
		buf.WriteByte(',')
	}
	if buf.Len() != 0 {
		w.line(buf.String())
	}
}

func (w *sourceWriter) writeInts(arr []int) {
	w.writeEls(len(arr), func(i int) string { return strconv.Itoa(arr[i]) })
}

func (w *sourceWriter) writeBytes(arr []byte) {
	w.line("[]byte{")
	w.writeEls(len(arr), func(i int) string { return strconv.Itoa(int(arr[i])) })
	w.line("},")
}

func (w *sourceWriter) writeStrings(arr []string) {
	w.line("[]string{")
	w.writeEls(len(arr), func(i int) string { return strconv.Quote(arr[i]) })
	w.line("},")
}

// writePacked writes a call that unpacks arr from 32-bit words, least
// significant bit first.
func (w *sourceWriter) writePacked(arr []bool) {
	packed := make([]int32, (len(arr)+31)/32)
	for i, bit := range arr {
		if bit {
			packed[i>>5] |= int32(uint32(1) << uint(i&0x1f))
		}
	}
	w.line("HTMLElementTablesUnpack([]int32{")
	w.writeEls(len(packed), func(i int) string { return strconv.Itoa(int(packed[i])) })
	w.line("}, " + strconv.Itoa(len(arr)) + "),")
}

func (w *sourceWriter) panicOnError() {
	w.lines(
		"if err != nil {",
		"panic(err)",
		"}",
	)
}

// object is a JSON object whose keys keep their order in the input, as the
// generator's output depends on it where two names share an element index.
// A repeated key keeps its first position and its last value.
type object struct {
	keys   []string
	values map[string]any
}

func (o *object) get(key string) (any, error) {
	v, ok := o.values[key]
	if !ok {
		return nil, fmt.Errorf("missing key %q", key)
	}
	return v, nil
}

func (o *object) object(key string) (*object, error) {
	v, err := o.get(key)
	if err != nil {
		return nil, err
	}
	obj, ok := v.(*object)
	if !ok {
		return nil, fmt.Errorf("%q is not an object", key)
	}
	return obj, nil
}

func (o *object) array(key string) ([]any, error) {
	v, err := o.get(key)
	if err != nil {
		return nil, err
	}
	arr, ok := v.([]any)
	if !ok {
		return nil, fmt.Errorf("%q is not an array", key)
	}
	return arr, nil
}

func (o *object) boolean(key string) (bool, error) {
	v, err := o.get(key)
	if err != nil {
		return false, err
	}
	b, ok := v.(bool)
	if !ok {
		return false, fmt.Errorf("%q is not a boolean", key)
	}
	return b, nil
}

func asString(v any) (string, error) {
	s, ok := v.(string)
	if !ok {
		return "", fmt.Errorf("%v is not a string", v)
	}
	return s, nil
}

// parseObject parses a JSON document whose top level is an object.
func parseObject(data []byte) (*object, error) {
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.UseNumber()
	v, err := parseValue(dec)
	if err != nil {
		return nil, err
	}
	if _, err := dec.Token(); err != io.EOF {
		return nil, errors.New("unexpected data after the top-level object")
	}
	obj, ok := v.(*object)
	if !ok {
		return nil, errors.New("the top level is not an object")
	}
	return obj, nil
}

// parseValue reads one JSON value: an *object, a []any, a string, a bool, a
// json.Number or nil.
func parseValue(dec *json.Decoder) (any, error) {
	tok, err := dec.Token()
	if err != nil {
		return nil, err
	}
	switch tok {
	case json.Delim('{'):
		obj := &object{values: map[string]any{}}
		for dec.More() {
			keyTok, err := dec.Token()
			if err != nil {
				return nil, err
			}
			key := keyTok.(string)
			v, err := parseValue(dec)
			if err != nil {
				return nil, err
			}
			if _, seen := obj.values[key]; !seen {
				obj.keys = append(obj.keys, key)
			}
			obj.values[key] = v
		}
		_, err := dec.Token()
		return obj, err
	case json.Delim('['):
		arr := []any{}
		for dec.More() {
			v, err := parseValue(dec)
			if err != nil {
				return nil, err
			}
			arr = append(arr, v)
		}
		_, err := dec.Token()
		return arr, err
	default:
		return tok, nil
	}
}
